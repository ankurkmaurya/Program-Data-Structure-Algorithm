	public static int[] assignTasks(int[] servers, int[] tasks) {
		int[] taskAssignedServerIndex = new int[tasks.length];

		PriorityQueue<int[]> availableServerQueue = new PriorityQueue<>((a, b) -> {
			if (a[0] == b[0]) {
				return a[1] - b[1];
			} else {
				return a[0] - b[0];
			}
		});

		PriorityQueue<int[]> busyServerQueue = new PriorityQueue<>((a, b) -> {
			if (a[0] == b[0]) {
				if (a[1] == b[1]) {
					return a[2] - b[2];
				} else {
					return a[1] - b[1];
				}
			} else {
				return a[0] - b[0];
			}
		});

		for (int sIndex = 0; sIndex < servers.length; sIndex++) {
			availableServerQueue.add(new int[] {servers[sIndex], sIndex});
		}
		
		int runningtime = 0;
		for(int taskIndex = 0; taskIndex < tasks.length; taskIndex++) {
			runningtime = Math.max(runningtime, taskIndex);
			
			while(!busyServerQueue.isEmpty() && busyServerQueue.peek()[0] == runningtime) {
				int[] freeServer = busyServerQueue.poll();
				availableServerQueue.add(new int[] {freeServer[1], freeServer[2]});
			}
			
			if(availableServerQueue.isEmpty()) {
				runningtime = busyServerQueue.peek()[0];
				while(!busyServerQueue.isEmpty() && busyServerQueue.peek()[0] == runningtime) {
					int[] freeServer = busyServerQueue.poll();
					availableServerQueue.add(new int[] {freeServer[1], freeServer[2]});
				}
			}
			
			int[] server = availableServerQueue.poll();
			int serverFreeTime = runningtime + tasks[taskIndex];
			busyServerQueue.add(new int[] {serverFreeTime, server[0], server[1]});
			taskAssignedServerIndex[taskIndex] = server[1];
		}
		
		return taskAssignedServerIndex;
	}
	
	
